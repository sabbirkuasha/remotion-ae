import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Scene } from "./ir.ts";

const BUILDER = fileURLToPath(new URL("../ae/builder.jsx", import.meta.url));

/** JSON as ASCII-only JavaScript: ExtendScript reads script files with a locale-dependent encoding. */
export function asciiLiteral(value: unknown): string {
  return JSON.stringify(value).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
}

export type BuildOptions = { replace?: boolean; noViewer?: boolean };

/**
 * A self-contained ExtendScript file that builds the scene when run in After Effects.
 * Its result is the build summary, followed by the value of `after` (an expression run after the build).
 */
export function sceneScript(scene: Scene, options: BuildOptions = {}, after?: string): string {
  return [
    `// ${scene.name}: generated by remotion-ae. In After Effects: File > Scripts > Run Script File...`,
    readFileSync(BUILDER, "utf8"),
    `var remotionAESummary = remotionAE.build(${asciiLiteral(scene)}, ${asciiLiteral(options)});`,
    after ? `remotionAESummary + "\\n" + (${after});` : "remotionAESummary;",
    "",
  ].join("\n");
}
